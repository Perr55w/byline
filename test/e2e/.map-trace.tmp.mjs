import { loadPlaywright, openPage, gotoRoute, setHash, sleep } from './lib/browser.mjs';
import { PHONE } from './lib/selectors.mjs';
const base = 'http://127.0.0.1:' + (process.argv[2] || 4462);
const route = process.argv[3] || 'map';
const { chromium } = loadPlaywright();
const browser = await chromium.launch();
const P = await openPage(browser, { profile: PHONE, throttle: 4 });
await gotoRoute(P.page, base, 'today', { settle: 2500 });
await setHash(P.page, '#/feed'); await sleep(1500);
await browser.startTracing(P.page, { categories: ['devtools.timeline', 'disabled-by-default-devtools.timeline'] });
await setHash(P.page, `#/${route}`); await sleep(1200);
const buf = await browser.stopTracing();
const ev = JSON.parse(buf.toString()).traceEvents;
const main = new Set(ev.filter(e => e.ph === 'M' && e.name === 'thread_name' && e.args?.name === 'CrRendererMain').map(e => `${e.pid}:${e.tid}`));
const X = ev.filter(e => main.has(`${e.pid}:${e.tid}`) && e.ph === 'X' && e.dur > 1500);
const t0 = Math.min(...X.map(e => e.ts));
for (const e of X.sort((a, b) => a.ts - b.ts)) if (['Layout', 'UpdateLayoutTree', 'Paint', 'PrePaint', 'Layerize', 'FunctionCall', 'TimerFire', 'FireAnimationFrame', 'EventDispatch', 'RunTask', 'HitTest', 'IntersectionObserverController::computeIntersections', 'Commit', 'ParseHTML', 'UpdateLayer', 'CompositeLayers'].includes(e.name) || e.dur > 5000) console.log(((e.ts - t0) / 1000).toFixed(1), e.name, (e.dur / 1000).toFixed(1), e.args?.data?.url?.split('/').pop() || e.args?.data?.functionName || '', e.args?.beginData?.frame ? '' : '');
await P.close(); await browser.close();
